#!/usr/bin/env python3
"""Generate docs/03-paper-tables.md and paper/*.tex longtables from data/*.csv (no hand-typed numbers)."""
import csv
from collections import Counter
from pathlib import Path

R = Path(__file__).resolve().parent.parent
rd = lambda n: list(csv.DictReader((R / "data" / n).open(encoding="utf-8")))
summ = rd("mapping-summary.csv"); pset = rd("wikibase-property-set.csv")
cm = rd("codemeta-terms-to-wikibase.csv"); wp = rd("wikidata-software-to-wikibase.csv")
st = Counter(r["status"] for r in pset)
esc = lambda s: (s or "").replace("|", "\\|")
tex = lambda s: (s or "").replace("\\", "").replace("&", "\\&").replace("_", "\\_").replace("#", "\\#").replace("%", "\\%")

L = ["# 03 Paper tables", "", "Generated by `tools/build_paper_tables.py` from `data/*.csv`; do not edit by hand.", "",
     "## Table A -- Composition of the Wikibase property set", "", "| Metric | Value |", "|---|---|"]
for r in summ:
    L.append(f"| {esc(r['metric'].strip())} | {r['value']} |")
L += ["", "## Table B -- Every CodeMeta term and where it went", "",
      "Status: `crosswalked` = CodeMeta term meets a Wikidata property; `codemeta-only` = no Wikidata property, new Wikibase property.", "",
      "| CodeMeta term | Group | In workbook | Status | Wikidata property | Wikibase property | Datatype | Phase |", "|---|---|---|---|---|---|---|---|"]
for r in cm:
    pid = f"{r['wikidata_pid']} {r['wikidata_label']}".strip()
    L.append(f"| {esc(r['codemeta_term'])} | {r['codemeta_group']} | {r['in_reviewed_workbook']} | {r['status']} | {esc(pid)} | {esc(r['wikibase_property'])} | {r['wikibase_datatype']} | {r['phase']} |")
L += ["", "## Table C -- WikiProject Software list and its CodeMeta counterparts", "",
      "| Wikidata property | Label | WikiProject category | Status | CodeMeta term(s) | Wikibase property |", "|---|---|---|---|---|---|"]
for r in wp:
    L.append(f"| {r['wikidata_pid']} | {esc(r['wikidata_label'])} | {esc(r['wikiproject_category'])} | {r['status']} | {esc(r['codemeta_terms'])} | {esc(r['wikibase_property'])} |")
L += ["", "## Table D -- Properties added on top (in neither vocabulary, or outside the WikiProject list)", "",
      "| Wikibase property | Wikidata property | Status | Origin | Note |", "|---|---|---|---|---|"]
for r in pset:
    if r["status"] == "chublets-addition" or (r["status"] == "wikidata-only" and r["in_wikiproject_software"] != "yes"):
        L.append(f"| {esc(r['wb_label'])} | {r['wikidata_pid']} | {r['status']} | {esc(r['wikidata_origin'])} | {esc(r['note'])} |")
br = rd("datacite-wikidata-bridge.csv")
L += ["", "## Table E -- CodeMeta as hub: Wikidata property and DataCite 4.6 element side by side (ConnOSS crosswalk S9)", "",
      "DataCite <-> Wikidata is not a published pair; it is derived through the shared CodeMeta term.", "",
      "| CodeMeta term | Wikidata property | DataCite element | Bridge |", "|---|---|---|---|"]
for r in br:
    L.append(f"| {esc(r['codemeta_term'])} | {esc(r['wikidata_cell'])} | {esc(r['datacite_cell'])[:110]} | {r['bridge']} |")
(R / "docs" / "03-paper-tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")

def longtable(name, cols, rows, caption, label):
    s = [f"% generated by tools/build_paper_tables.py -- {name}", f"\\begin{{longtable}}{{{'l' * len(cols)}}}", f"\\caption{{{caption}}}\\label{{{label}}}\\\\", "\\hline",
         " & ".join(tex(c) for c in cols) + " \\\\ \\hline \\endhead"]
    s += [" & ".join(tex(x) for x in r) + " \\\\" for r in rows]
    s += ["\\hline", "\\end{longtable}"]
    (R / "paper" / name).write_text("\n".join(s) + "\n", encoding="utf-8")

longtable("table-codemeta.tex", ["CodeMeta term", "Status", "Wikidata", "Wikibase property"],
          [(r["codemeta_term"], r["status"], r["wikidata_pid"] or "--", r["wikibase_property"]) for r in cm],
          "Every CodeMeta term and its fate in the Wikibase property set.", "tab:codemeta-terms")
longtable("table-wikiproject.tex", ["Wikidata", "Label", "Status", "CodeMeta term"],
          [(r["wikidata_pid"], r["wikidata_label"], r["status"], r["codemeta_terms"] or "--") for r in wp],
          "WikiProject Software properties and their CodeMeta counterparts.", "tab:wikiproject")
print("wrote docs/03-paper-tables.md and paper/*.tex")
